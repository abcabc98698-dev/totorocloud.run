export function getBrandBySlug(slug: string): AirportBrand | undefined {
  return AIRPORT_BRANDS.find(
    (b) =>
      b.slug.toLowerCase() === slug.toLowerCase() ||
      b.id.toLowerCase() === slug.toLowerCase(),
  );
}
